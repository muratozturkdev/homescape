import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath, URL } from 'node:url'
import tailwindcss from '@tailwindcss/vite'
import react from '@vitejs/plugin-react'
import { defineConfig, loadEnv, type Plugin, type ProxyOptions } from 'vite'

/**
 * Development: writes the active plan of a browser to a local file (.homescape-dump/plan-<browser>.json; ignored by git),
 * to read the plan from your own browser while debugging. The data never leaves the machine; it runs only in the dev
 * server (src/dev/planDump.ts sends it).
 */
function planDump(): Plugin {
  return {
    name: 'homescape-plan-dump',
    apply: 'serve',
    configureServer(server) {
      server.ws.on('homescape:plan', (data: { browser?: string }) => {
        try {
          const name = String(data?.browser ?? 'browser').replace(/[^a-z0-9-]/gi, '').slice(0, 40) || 'browser'
          mkdirSync('.homescape-dump', { recursive: true })
          writeFileSync(`.homescape-dump/plan-${name}.json`, JSON.stringify(data, null, 1))
        } catch {
          /* could not write */
        }
      })
    },
  }
}

/**
 * Demo site (`npm run build:site`, src/site.ts): the page title, description and link previews for
 * homescape.muratozturk.dev; the preview image (docs/screenshots/social-preview.png) goes out as og.png and the promo video
 * (docs/media/promo.mp4, linked from the README) as promo.mp4. Only site builds carry them, not the Home Assistant app.
 */
const SITE_URL = 'https://homescape.muratozturk.dev/'
function siteMeta(): Plugin {
  const title = 'Homescape: your Home Assistant home as a live 3D dollhouse'
  const description =
    'Try the live demo of Homescape, an open source 3D dollhouse for Home Assistant. Every object is generated by code written by AI, and it runs fully local: no cloud, no account.'
  const meta = (attrs: Record<string, string>) => ({ tag: 'meta', attrs, injectTo: 'head' as const })
  return {
    name: 'homescape-site-meta',
    transformIndexHtml(html) {
      return {
        html: html.replace(/<title>[^<]*<\/title>/, `<title>${title}</title>`).replace(/<meta name="description" content="[^"]*" \/>/, `<meta name="description" content="${description}" />`),
        tags: [
          { tag: 'link', attrs: { rel: 'canonical', href: SITE_URL }, injectTo: 'head' },
          meta({ property: 'og:type', content: 'website' }),
          meta({ property: 'og:site_name', content: 'Homescape' }),
          meta({ property: 'og:title', content: title }),
          meta({ property: 'og:description', content: description }),
          meta({ property: 'og:url', content: SITE_URL }),
          meta({ property: 'og:image', content: `${SITE_URL}og.png` }),
          meta({ property: 'og:image:width', content: '1280' }),
          meta({ property: 'og:image:height', content: '640' }),
          meta({ name: 'twitter:card', content: 'summary_large_image' }),
        ],
      }
    },
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: 'og.png', source: readFileSync('docs/screenshots/social-preview.png') })
      this.emitFile({ type: 'asset', fileName: 'promo.mp4', source: readFileSync('docs/media/promo.mp4') })
    },
  }
}

/*
 * With HA_URL (.env.local) the dev server proxies Home Assistant: the browser sees everything on one origin, so no CORS
 * setup is needed and Home Assistant's own login page (OAuth) works through this address.
 */
const HA_PATHS = ['/api', '/auth', '/frontend_latest', '/frontend_es5', '/static', '/manifest.json', '/sw-modern.js']

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), '')
  const target = env.HA_URL?.replace(/\/$/, '') ?? ''
  const proxy: Record<string, ProxyOptions> | undefined = target
    ? Object.fromEntries(HA_PATHS.map((p) => [p, { target, changeOrigin: true, ws: p === '/api' }]))
    : undefined

  return {
    // Relative paths: so it also works under the sub path of the Home Assistant app (ingress).
    base: './',
    plugins: [react(), tailwindcss(), planDump(), ...(mode === 'site' ? [siteMeta()] : [])],
    resolve: { alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) } },
    define: { __HA_PROXY_TARGET__: JSON.stringify(target) },
    server: { port: 5190, strictPort: true, proxy },
    preview: { port: 5190, strictPort: true, proxy },
  }
})
